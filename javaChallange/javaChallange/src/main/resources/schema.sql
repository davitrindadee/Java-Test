
CREATE TABLE IF NOT EXISTS T_SG_USUARIO (
                                            ID_USUARIO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            NM_USUARIO VARCHAR(100) NOT NULL,
    DS_SENHA VARCHAR(255) NOT NULL,
    DS_EMAIL VARCHAR(150) NOT NULL,
    NR_IDADE INTEGER NOT NULL,
    DS_CIDADE VARCHAR(100) NOT NULL,
    DS_INTERESSE VARCHAR(150) NOT NULL,
    NR_PONTOS INTEGER DEFAULT 0 NOT NULL
    );

CREATE TABLE IF NOT EXISTS T_SG_ACAO (
                                         ID_ACAO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         NM_ACAO VARCHAR(100) NOT NULL,
    DS_ACAO VARCHAR(255),
    NR_PONTOS INTEGER NOT NULL,
    ST_ACAO INTEGER NOT NULL
    );

CREATE TABLE IF NOT EXISTS T_SG_MISSAO (
                                           ID_MISSAO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           NM_MISSAO VARCHAR(100) NOT NULL,
    DS_MISSAO VARCHAR(255),
    NR_PONTOS INTEGER NOT NULL,
    ST_MISSAO INTEGER NOT NULL
    );

CREATE TABLE IF NOT EXISTS T_SG_AVATAR (
                                           ID_AVATAR INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           ID_USUARIO INTEGER NOT NULL,
                                           NM_AVATAR VARCHAR(100) NOT NULL,
    NR_NIVEL INTEGER NOT NULL,
    CONSTRAINT FK_AVATAR_USUARIO
    FOREIGN KEY (ID_USUARIO)
    REFERENCES T_SG_USUARIO(ID_USUARIO)
    );

CREATE TABLE IF NOT EXISTS T_SG_INTERACAO (
                                              ID_INTERACAO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              ID_USUARIO INTEGER NOT NULL,
                                              ID_ACAO INTEGER NOT NULL,
                                              DS_TIPO VARCHAR(100) NOT NULL,
    DT_INTERACAO TIMESTAMP NOT NULL,
    CONSTRAINT FK_INTERACAO_USUARIO
    FOREIGN KEY (ID_USUARIO)
    REFERENCES T_SG_USUARIO(ID_USUARIO),
    CONSTRAINT FK_INTERACAO_ACAO
    FOREIGN KEY (ID_ACAO)
    REFERENCES T_SG_ACAO(ID_ACAO)
    );

CREATE TABLE IF NOT EXISTS T_SG_PONTUACAO (
                                              ID_PONTUACAO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              ID_USUARIO INTEGER NOT NULL,
                                              NR_PONTOS INTEGER NOT NULL,
                                              DT_PONTUACAO TIMESTAMP NOT NULL,
                                              CONSTRAINT FK_PONTUACAO_USUARIO
                                              FOREIGN KEY (ID_USUARIO)
    REFERENCES T_SG_USUARIO(ID_USUARIO)
    );
